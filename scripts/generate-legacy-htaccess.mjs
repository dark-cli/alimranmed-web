#!/usr/bin/env node
/**
 * Generate Apache .htaccess redirect rules for the old WordPress sites
 * (alimranmed.com, ar.alimranmed.com) → alimran.clinic, one file per host.
 *
 * Source of truth is each content entry's `legacyUrl` frontmatter. The
 * specific rules are followed by catch-alls: WP uploads → /images/legacy/
 * (the migrated copies keep the same year/month paths) and everything else
 * → the matching locale home. wp-admin / wp-login stay reachable so the old
 * install can still be managed during the move.
 *
 * Old URLs whose slug changed (dated blog permalinks, /archives/<id> on the
 * AR site, renamed pages) can't be derived from legacyUrl; those live in
 * redirects/legacy-extra.json — a reviewed map of old path → new path,
 * built by matching old-sitemap page titles to content titles.
 *
 * Run: node scripts/generate-legacy-htaccess.mjs
 * Output goes in redirects/<host>.htaccess. Paste the rules ABOVE the
 * "# BEGIN WordPress" block in that host's .htaccess.
 */

import { readFile, readdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const CONTENT = path.join(REPO_ROOT, "src", "content");
const OUT_DIR = path.join(REPO_ROOT, "redirects");
const NEW_SITE = "https://alimran.clinic";

// Collections with a route, and how an entry maps to its URL path.
const ROUTES = {
  blog: (topic) => `blog/${topic}/`,
  cases: (topic) => `cases/${topic}/`,
  doctors: (topic) => `doctors/${topic}/`,
  services: (topic) => `services/${topic}/`,
  treatments: (topic) => `treatments/${topic}/`,
  pages: () => "about/", // about + its mission/values/vision sub-pages
};
const HOST_LOCALE = { "alimranmed.com": "en", "ar.alimranmed.com": "ar" };

async function* walk(dir) {
  for (const name of await readdir(dir)) {
    const p = path.join(dir, name);
    if ((await stat(p)).isDirectory()) yield* walk(p);
    else if (/^(en|ar)\.mdx?$/.test(name)) yield p;
  }
}

/** Normalise a legacyUrl into { host, path } (decoded), or null if unusable. */
function parseLegacy(raw) {
  let url = raw.trim();
  // Some Arabic entries lost their scheme/host and gained a stray "%".
  if (/^%%[0-9a-f]{2}/i.test(url)) url = `https://ar.alimranmed.com/${url.slice(1)}`;
  if (!/^https?:\/\//.test(url)) return null;
  const u = new URL(url);
  const host = u.hostname.replace(/^www\./, "");
  if (!(host in HOST_LOCALE)) return null;
  let p;
  try { p = decodeURIComponent(u.pathname); } catch { return null; }
  p = p.replace(/^\/+|\/+$/g, "");
  return p ? { host, path: p } : null;
}

const rules = { "alimranmed.com": new Map(), "ar.alimranmed.com": new Map() };
const skipped = [];

for (const [collection, toPath] of Object.entries(ROUTES)) {
  for await (const file of walk(path.join(CONTENT, collection))) {
    const src = await readFile(file, "utf8");
    const m = src.match(/^legacyUrl:\s*"?([^"\n]+)"?\s*$/m);
    if (!m) continue;
    const rel = path.relative(path.join(CONTENT, collection), file);
    const locale = path.basename(file).slice(0, 2);
    const topic = path.dirname(rel);
    const tail = toPath(topic);
    const legacy = parseLegacy(m[1]);
    if (!tail || !legacy) { skipped.push(`${collection}/${rel}: ${m[1]}`); continue; }
    const target = `${NEW_SITE}/${locale}/${tail}`;
    const existing = rules[legacy.host].get(legacy.path);
    // Prefer the entry whose locale matches the old host (the AR file of an
    // EN-site article is usually a fallback copy of the same page).
    if (!existing || (locale === HOST_LOCALE[legacy.host] && !existing.localeMatch)) {
      rules[legacy.host].set(legacy.path, { target, localeMatch: locale === HOST_LOCALE[legacy.host] });
    }
  }
}

const extra = JSON.parse(await readFile(path.join(OUT_DIR, "legacy-extra.json"), "utf8"));
for (const [host, map] of Object.entries(extra)) {
  for (const [p, target] of Object.entries(map)) {
    if (!rules[host].has(p)) rules[host].set(p, { target: `${NEW_SITE}${target}`, localeMatch: true });
  }
}

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

for (const [host, map] of Object.entries(rules)) {
  const locale = HOST_LOCALE[host];
  const lines = [
    `# ${host} → alimran.clinic — generated by scripts/generate-legacy-htaccess.mjs`,
    `# Paste ABOVE the "# BEGIN WordPress" block. ${map.size} page rules + catch-alls.`,
    "",
    "<IfModule mod_rewrite.c>",
    "RewriteEngine On",
    "",
    "# Keep the old WordPress admin reachable during the move.",
    "RewriteRule ^(wp-admin|wp-login\\.php|wp-json)(/|$) - [L]",
    "",
    "# Home",
    `RewriteRule ^$ ${NEW_SITE}/${locale}/ [R=301,L]`,
    "",
    "# Pages",
    ...[...map.entries()]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([p, { target }]) => `RewriteRule ^${esc(p)}/?$ ${target} [R=301,L,NE]`),
    "",
    "# Media: WP uploads were migrated to /images/legacy/ with the same paths.",
    `RewriteRule ^wp-content/uploads/(.*)$ ${NEW_SITE}/images/legacy/$1 [R=301,L,NE]`,
    "",
    "# Everything else (categories, tags, feeds, unmapped pages) → locale home.",
    `RewriteRule ^ ${NEW_SITE}/${locale}/ [R=301,L]`,
    "</IfModule>",
    "",
  ];
  await writeFile(path.join(OUT_DIR, `${host}.htaccess`), lines.join("\n"));
  console.log(`Wrote redirects/${host}.htaccess (${map.size} page rules)`);
}
if (skipped.length) console.log(`Skipped ${skipped.length} entries with unusable legacyUrl:\n  ${skipped.join("\n  ")}`);
