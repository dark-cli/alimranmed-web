#!/usr/bin/env node
/**
 * Generate public/_redirects (Cloudflare Workers Assets format).
 *
 * Cloudflare Workers Assets limit: 100 rules total.
 * We only emit the essential rules — locale roots and catch-alls.
 * Individual legacy WP path redirects are omitted; the catch-alls
 * handle bare /treatments/* and /services/* paths instead.
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const OUT = path.join(REPO_ROOT, "public", "_redirects");

const { NAV, flattenNav } = await import(
  path.join(REPO_ROOT, "src/data/navigation.ts")
);

const lines = [
  "# Auto-generated by scripts/generate-redirects.mjs — do not edit by hand.",
  "# Every legacy WordPress URL redirects to the new-site equivalent.",
  "",
  "# ── Locale root redirects ──────────────────────────────────────────────",
  "# Serve real HTTP 301s at the CDN edge so Google can consolidate canonicals",
  "# without seeing Astro's static meta-refresh HTML page for `Astro.redirect()`.",
  "/          /en/       301",
  "/en        /en/       301",
  "/ar        /ar/       301",
  "",
  "# ── Locale-less path catch-alls ────────────────────────────────────────",
  "# Bare /treatments/* and /services/* originate from legacy redirects below",
  "# and from internal markdown links in content files. Route them to English.",
  "/treatments/*  /en/treatments/:splat  301",
  "/services/*    /en/services/:splat    301",
  "/blog/*        /en/blog/:splat        301",
  "",
];

lines.push("");
await writeFile(OUT, lines.join("\n"));
console.log(`Wrote _redirects (6 essential rules) to ${path.relative(REPO_ROOT, OUT)}`);
