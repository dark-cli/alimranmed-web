#!/usr/bin/env node
/**
 * Generate public/_redirects (Cloudflare Workers Assets format).
 *
 * Cloudflare Workers Assets limit: 100 rules total.
 * We only emit the essential rules — locale roots and catch-alls.
 * Individual legacy WP path redirects are omitted; the catch-alls
 * handle bare /treatments/* and /services/* paths instead.
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..");
const OUT = path.join(REPO_ROOT, "public", "_redirects");

const { NAV, flattenNav } = await import(
  path.join(REPO_ROOT, "src/data/navigation.ts")
);

const lines = [
  "# Auto-generated by scripts/generate-redirects.mjs — do not edit by hand.",
  "# Every legacy WordPress URL redirects to the new-site equivalent.",
  "",
  "# ── Locale root redirects ──────────────────────────────────────────────",
  "# Serve real HTTP 301s at the CDN edge so Google can consolidate canonicals",
  "# without seeing Astro's static meta-refresh HTML page for `Astro.redirect()`.",
  "/          /en/       301",
  "/en        /en/       301",
  "/ar        /ar/       301",
  "",
  "# ── Locale-less path catch-alls ────────────────────────────────────────",
  "# Bare /treatments/* and /services/* originate from legacy redirects below",
  "# and from internal markdown links in content files. Route them to English.",
  "/treatments/*  /en/treatments/:splat  301",
  "/services/*    /en/services/:splat    301",
  "/blog/*        /en/blog/:splat        301",
  "",
];

// ── Merged duplicate pages ──────────────────────────────────────────────
// Pages that duplicated another page's content were removed; each old path
// 301s to the page that was kept. Applies to both locales.
const MERGED = [
  ["services/brain-stimulation/tms-alzheimer", "blog/tms-for-alzheimer-disease"],
  ["blog/tms-for-migraine", "services/brain-stimulation/tms-migraine"],
  ["blog/tms-for-pains", "services/brain-stimulation/tms-pain"],
  ["blog/amyotrophic-lateral-sclerosis-als-2", "treatments/als"],
  ["blog/tms-for-tinnitus-2", "services/brain-stimulation/tms-tinnitus"],
  ["blog/tms-for-tinnitus", "services/brain-stimulation/tms-tinnitus"],
  ["services/surgery/acdf", "services/surgery/anterior-cervical-discectomy-and-fusion"],
  ["treatments/nervous-bladder", "treatments/neurogenic-bladder"],
  ["services/natural-therapy", "blog/physiotherapy"],
  ["services/physiotherapy/physiotherapy-3", "blog/physiotherapy"],
  ["services/surgery/arthroplasty", "services/surgery/artificial-disc"],
  ["services/physiotherapy/shortwave", "services/physiotherapy/shortwave-therapy"],
  ["services/brain-stimulation/tms-neuropsychiatric", "blog/tms-for-neuropsychiatric-disorders"],
  ["services/surgery/intrathecal-pump", "blog/what-is-an-intrathecal-pump"],
  ["services/radiofrequency/radiofrequency-2", "services/radiofrequency/radiofrequency"],
  ["services/exercises/exercises-2", "services/exercises"],
  ["services/surgery/surgery", "services/surgery"],
];
lines.push("# ── Merged duplicate pages ─────────────────────────────────────────────");
for (const [from, to] of MERGED) {
  for (const locale of ["en", "ar"]) {
    lines.push(`/${locale}/${from}/  /${locale}/${to}/  301`);
  }
}

lines.push("");
await writeFile(OUT, lines.join("\n"));
const ruleCount = lines.filter((l) => l.startsWith("/")).length;
console.log(`Wrote _redirects (${ruleCount} rules) to ${path.relative(REPO_ROOT, OUT)}`);
